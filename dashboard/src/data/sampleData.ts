export const generateNewSubmission = (project: ProjectId): Submission => {
  const now = new Date();
  const base: Submission = {
    id: `${project}-${Math.floor(Math.random() * 9000) + 1000}`,
    project,
    submissionDate: now.toISOString(),
    startTime: new Date(now.getTime() - 20 * 60000).toISOString(),
    endTime: now.toISOString(),
    caseId: `${project.substring(0, 1)}-${Math.floor(Math.random() * 9000) + 1000}`,
    enumerator: `enum_0${Math.floor(Math.random() * 5) + 1}`,
    durationMinutes: 20 + Math.floor(Math.random() * 15),
    status: randomStatus(),
  };

  if (project === 'FARMER') {
    return {
      ...base,
      db5Age: 18 + Math.floor(Math.random() * 40),
      db6AgeCategory: ['18-35', '36-50', '50+'][Math.floor(Math.random() * 3)],
      db7Gender: Math.random() > 0.5 ? 'Female' : 'Male',
      db10District: ['Kigali', 'Kampala', 'Dodoma'][Math.floor(Math.random() * 3)],
      db11Region: ['Eastern', 'Northern', 'Central'][Math.floor(Math.random() * 3)],
      db14Village: ['Kawangware', 'Lira', 'Arusha'][Math.floor(Math.random() * 3)],
    };
  }

  if (project === 'ENTERPRISE') {
    return {
      ...base,
      b2MaleOwnerAge: 25 + Math.floor(Math.random() * 30),
      b3FemaleOwnerAge: 25 + Math.floor(Math.random() * 30),
      a10RespondentGender: Math.random() > 0.5 ? 'Female' : 'Male',
      b1OwnerGender: ['Female', 'Male', 'Mixed'][Math.floor(Math.random() * 3)],
      b14District: ['Accra', 'Tamale', 'Kumasi'][Math.floor(Math.random() * 3)],
      validationStatus: Math.random() > 0.2 ? 'validated' : 'pending_validation',
    };
  }

  return {
    ...base,
    d4Sex: Math.random() > 0.5 ? 'Female' : 'Male',
    d9LocationType: ['Urban', 'Rural', 'Peri-urban'][Math.floor(Math.random() * 3)],
    d8Latitude: 5 + Math.random(),
    d8Longitude: -1 + Math.random(),
    engagementType: ['Farming', 'Off-farm ag', 'Non-agric'][Math.floor(Math.random() * 3)],
  };
};

